"""Durable DBTL workflow contracts (Phases 3–8).

This package holds the *pure* workflow rules — the state machine a human drives
today and the Supervisor Graph drives tomorrow, plus the Phase 6 stage
contracts: which capabilities a stage needs, what a worker must return, and
when reconciled data is fit for Build. It deliberately owns no storage and no
agent code, so every caller shares one definition of what is legal.

Storage lives in ``deerflow.persistence.dbtl``; the supervisor and orchestrator
graphs live in ``deerflow.agents.dbtl``.
"""

